function wrap(text, font, size, maxW, maxLines) {
  const out = [];
  String(text).split(/\r?\n/).forEach(par => {
    let line = '';
    par.split(/\s+/).forEach(w => {
      const t = line ? line + ' ' + w : w;
      if (font.widthOfTextAtSize(t, size) <= maxW) line = t;
      else { if (line) out.push(line); line = w; while (font.widthOfTextAtSize(line, size) > maxW && line.length > 1) line = line.slice(0, -1); }
    });
    if (line) out.push(line);
  });
  return out.slice(0, maxLines);
}

let templateBytes = null;
async function buildCopy(L, pageIdx) {
  templateBytes = templateBytes || fs.readFileSync(TEMPLATE);
  const out = await PDFDocument.create(); const src = await PDFDocument.load(templateBytes);
  const pages = await out.copyPages(src, pageIdx); pages.forEach(p => out.addPage(p));
  const font = await out.embedFont(StandardFonts.Helvetica); const bold = await out.embedFont(StandardFonts.HelveticaBold);
  const page = out.getPage(0); const ink = rgb(0.05, 0.05, 0.2);
  const clean = s => String(s == null ? '' : s).replace(/[^\n\x20-\x7E\u00A0-\u00FF\u2013\u2014\u2019]/g, ''); // keep newlines; Helvetica can't render Devanagari etc.
  const draw = (txt, x, yTop, size, maxW, opt = {}) => {
    const f = opt.bold ? bold : font;
    wrap(clean(txt), f, size, maxW, opt.lines || 1).forEach((ln, i) => page.drawText(ln, { x, y: PAGE_H - yTop - (opt.lh || size + 2) * i, size, font: f, color: ink }));
  };
  const D = { ...L };
  D.consignorBlock = [L.consignorName, L.consignorAddr].filter(Boolean).join('\n');
  D.consigneeBlock = [L.consigneeName, L.consigneeAddr].filter(Boolean).join('\n');
  D.consignorSignName = L.consignorSignName || L.consignorName;
  // optional consignor contact person / mobile – printed on the last line of the consignor box
  const cLine = [L.consignorContact, L.consignorMobile ? 'Mob: ' + L.consignorMobile : ''].filter(Boolean).join('  |  ');
  if (cLine) draw(cLine, 87, 385 + 7 * 10.5, 8, 236, { bold: true });
  D.supervisorSign = 'Generated by ' + (L.supervisorName || '') + ' · LS App · ' + (L.generatedAt || '');
  D.unitActual = L.unit || ''; D.unitCharged = L.unit || '';
  if (L.gstInvoiceNo) D.invoiceNo = [L.invoiceNo, 'GST Inv: ' + L.gstInvoiceNo].filter(Boolean).join('  |  ');
  // Issuing branch: the template carries Dronagiri's block. For any other branch, cover it and print that branch.
  const br = String(L.branch || '').toUpperCase();
  let b = null; /* BRFIX19 */ try { b = br && DBX && DBX.prepare('SELECT * FROM branches WHERE upper(name)=?').get(br); } catch (e) {}
  if (br && (br !== 'DRONAGIRI' || (b && b.address))) {
    page.drawRectangle({ x: 183.5, y: PAGE_H - 172, width: 251, height: 66, color: rgb(1, 1, 1) });
    draw('Issuing Branch: ' + br, 188, 116, 8.5, 244, { bold: true });
    if (b && b.address) draw('Address: ' + b.address, 188, 128, 7.5, 244, { lines: 3, lh: 9 });
    const ph = [b && b.phone ? 'Ph: ' + b.phone : '', b && b.email ? 'Email: ' + b.email : ''].filter(Boolean);
    ph.forEach((t, i) => draw(t, 188, 158 + 9 * i, 7.5, 244));
  }
  FIELDS.forEach(([k, x, y, sz, w, opt]) => { if (D[k]) draw(D[k], x, y, sz, w, opt); });
  let IT = (L.items || []).filter(i => i.product || i.pkgs);
  const totPk = IT.reduce((a, i) => a + (parseFloat(i.pkgs) || 0), 0);
  if (IT.length > ITEM_ROWS) { const rest = IT.slice(ITEM_ROWS - 1); IT = IT.slice(0, ITEM_ROWS - 1).concat([{ product: '+' + rest.length + ' more items', pkgs: String(rest.reduce((a, i) => a + (parseFloat(i.pkgs) || 0), 0) || ''), type: '' }]); }
  IT.forEach((it, i) => { const yb = 626.6 + 13.1 * i + 9.5; draw(it.product, 27, yb - 4.2, 5.1, 66, { lines: 2, lh: 5.4 }); draw(it.pkgs, 95, yb, 6.5, 32); draw(it.type, 131, yb, 6.2, 40); });
  if (totPk && (L.items || []).length > 1) draw('Total pkgs: ' + totPk, 95, 626.6 + 13.1 * ITEM_ROWS + 6, 6.5, 80, { bold: true });
  if (/^(paid|to pay)$/i.test(String(L.basis || '').trim())) RATE_ROWS.forEach(([k, yb]) => { if (L.rates && L.rates[k]) draw(L.rates[k], 250, yb, 6.5, 100); }); // freight prints only for Paid / To Pay
  out.setTitle('Best Roadways LR ' + (L.cnNo || '')); out.setProducer('BRL Loading Supervisor App');
  return Buffer.from(await out.save());
}

async function buildLrPdfs(L) {
  const [consignee, driver, consignor] = await Promise.all([buildCopy(L, [2, 3]), buildCopy(L, [4, 5]), buildCopy(L, [0, 1])]);
  return { consignee, driver, consignor };
}
